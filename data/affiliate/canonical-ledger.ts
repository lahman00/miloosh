/**
 * CANONICAL AFFILIATE LEDGER (2026-08-21)
 *
 * Single source of truth for every affiliate program relationship across Miloosh.
 * One record per PROGRAM RELATIONSHIP (portfolio programs cover multiple product slugs).
 * All counts and reports MUST be computed dynamically from this ledger.
 */

export type CanonicalLedgerStatus =
  | "ACTIVE"
  | "APPROVED_NEEDS_LINK"
  | "APPROVED_NEEDS_EDITORIAL_CONTENT"
  | "PENDING_REVIEW"
  | "READY_AND_VERIFIED"
  | "BLOCKED_FORM_DEFECT"
  | "OWNER_ACTION_REQUIRED"
  | "REJECTED"
  | "HOLD"
  | "NO_REAL_PROGRAM_FOUND"
  | "PROGRAM_NOT_VERIFIED"
  | "PROGRAM_ENDED"
  | "NOT_ELIGIBLE";

export interface AffiliateProgramRelationship {
  programId: string;
  programName: string;
  network: string;
  productSlugs: string[];
  status: CanonicalLedgerStatus;
  statusUpdatedAt: string;
  applicationSubmittedAt: string | null;
  /** Most recent evidenced owner follow-up while a relationship remains pending. */
  lastFollowupAt?: string | null;
  decisionAt: string | null;
  affiliateUrl: string | null;
  /** Exact issued destinations for a portfolio; a missing mapped product fails closed. */
  productAffiliateUrls?: Readonly<Record<string, string>>;
  commissionModel: string;
  cookieWindow: string | null;
  evidence: string[];
  ownerBlocker: string | null;
  formBlocker: string | null;
  eligibility: string | null;
  applicationUrl: string | null;
  notes: string;
}

export function getRelationshipAffiliateUrl(relationship: AffiliateProgramRelationship, slug: string): string | null {
  if (!relationship.productSlugs.includes(slug)) return null;
  if (relationship.productAffiliateUrls) return relationship.productAffiliateUrls[slug] ?? null;
  return relationship.affiliateUrl;
}

