/**
 * Regenerates data/seo/discovery-baseline.ts from a captured sitemap.xml.
 *
 *   npx tsx scripts/seo/capture-discovery-baseline.ts <sitemap.xml> <source-sha> <captured-at-utc>
 *
 * Writes only software slugs and comparison slugs. Every entry must resolve to a real software record or published
 * comparison and must pass the CURRENT strict indexing-quality gate, otherwise the capture is refused: the baseline
 * records URLs that were genuinely admitted on quality grounds, never thin pages.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { getAllSoftware } from "@/data/software";
import { PUBLISHED_COMPARISONS, getComparisonSlug } from "@/data/comparisons";
import { isSoftwareIndexingReady } from "@/lib/indexing-quality";

const [xmlPath, sourceSha, capturedAtUtc] = process.argv.slice(2);
if (!xmlPath || !sourceSha || !capturedAtUtc) {
  console.error("usage: capture-discovery-baseline.ts <sitemap.xml> <source-sha> <captured-at-utc>");
  process.exit(2);
}

const xml = readFileSync(xmlPath);
const locs = [...xml.toString("utf8").matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => new URL(m[1]).pathname);
const software = getAllSoftware();
const softwareBySlug = new Map(software.map((s) => [s.slug, s]));
const comparisonSlugs = new Set(PUBLISHED_COMPARISONS.map(([a, b]) => getComparisonSlug(a, b)));

const softwareSlugs = locs.filter((p) => p.startsWith("/software/")).map((p) => p.slice("/software/".length)).sort();
const compareSlugs = locs.filter((p) => p.startsWith("/compare/")).map((p) => p.slice("/compare/".length)).sort();

const problems: string[] = [];
for (const slug of softwareSlugs) {
  const record = softwareBySlug.get(slug);
  if (!record) problems.push(`software ${slug}: no record`);
  else if (!isSoftwareIndexingReady(record)) problems.push(`software ${slug}: fails the current strict gate`);
}
for (const slug of compareSlugs) {
  const pair = PUBLISHED_COMPARISONS.find(([a, b]) => getComparisonSlug(a, b) === slug);
  if (!pair || !comparisonSlugs.has(slug)) problems.push(`comparison ${slug}: not a published pair`);
  else if (!softwareSlugs.includes(pair[0]) || !softwareSlugs.includes(pair[1])) {
    problems.push(`comparison ${slug}: a product is not in the admitted software set`);
  }
}
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const list = (items: string[]) => items.map((item) => `    ${JSON.stringify(item)},`).join("\n");
const out = `/**
 * DISCOVERY-ADMISSION BASELINE — records which software and comparison URLs were actually submitted in the live
 * sitemap at capture time. It documents discovery continuity (these URLs were admitted on strict quality grounds),
 * NOT fact freshness: it never makes a stale price or date current. Only slugs are stored.
 *
 * Generated by scripts/seo/capture-discovery-baseline.ts from the captured sitemap; do not hand-edit. Consumed only
 * through lib/discovery-continuity.ts, which treats a malformed registry as empty (fail closed).
 */
export const DISCOVERY_BASELINE: {
  version: number;
  capturedAtUtc: string;
  sourceSha: string;
  sitemapSha256: string;
  software: readonly string[];
  comparisons: readonly string[];
} = {
  version: 1,
  capturedAtUtc: ${JSON.stringify(capturedAtUtc)},
  sourceSha: ${JSON.stringify(sourceSha)},
  sitemapSha256: ${JSON.stringify(createHash("sha256").update(xml).digest("hex"))},
  software: [
${list(softwareSlugs)}
  ],
  comparisons: [
${list(compareSlugs)}
  ],
};
`;
writeFileSync(new URL("../../data/seo/discovery-baseline.ts", import.meta.url), out);
console.log(`software=${softwareSlugs.length} comparisons=${compareSlugs.length}`);
